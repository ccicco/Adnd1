namespace rules {

// ---- the abyss pins ----

// the 666 layers of the Abyss - an estimate, but the Abyss definitely has the
// most layers and therefore potentially the most inhabitants of any of the
// outer planes; no sage or scholar claims to have visited or catalogued each
// layer, and each Power seems to claim at least one layer as its own, making
// further definition difficult; the plane combines all that is evil with all
// that is chaotic - an ugly, violent place where the strong survive only on
// the backs of the weak, the birthing place of the demonic races; called
// Demonholme by the natives of Gladsheim and Jurgarten (misshapen lands) by
// those of Arvandor.
inline int ddlAbyssLayerCount()
    { return 666; }

// the Abyssal-layers terrain table, band width: a character thrust into a
// random layer (by curse, item, or wrong conduit) rolls d100, with each of
// the eight full 10-point bands a terrain stretching on forever and inhabited
// by foul creatures - 1-10 desert (miles of black/white/red dust without end,
// no water, standard WSG dehydration chances unless rations are available),
// 11-20 glacier (miles of black/white/orange ice with few peaks, effects as
// the para-elemental plane of Ice), 21-30 spatial (no gravity, no native
// matter - air exists but nothing else), 31-40 maelstrom (Limbo-like churn
// and bubble, the same difficulties as Limbo, but a safe zone cannot be
// generated by any being of power less than a lesser god), 41-50 rocky (the
// typical lower-plane territory, lava regions with volcanoes), 51-60
// underground (pure solid rock burrowed and carved by its inhabitants;
// conduits in always land in areas of at least temporary safety), 61-70 water
// (an ocean with normal gravity and a surface that may be miles above the
// entry point), 71-80 normal terrain (the variety of a Prime Material plane).
inline int ddlTerrainBand()
    { return 10; }

// the terrain table tail, first half: 81-90 a layer of delusion - it appears
// Prime-like, but the layer itself is a sentient being seeking to destroy the
// invaders (poison flowers, attacking trees, friends-turned-assassins are
// common; DM deviousness encouraged); 91-95 the realm or palace of a powerful
// Abyssal creature, usually a demon prince but often a god-like Power -
// visitors are not appreciated, so the traveler in Demogorgon's court had
// best have a good story or a quick way out.
inline int ddlTerrainRealmEnd()
    { return 95; }

// the terrain table tail, second half: 96-00 a layer of evil incarnate -
// mortals of good alignment must successfully save vs spell or be slain;
// neutral mortals (and the good-aligned who make the saving throw) are flung
// into another layer randomly; mortals of evil nature are transformed into
// bodaks with no saving throw.
inline int ddlTerrainEvilEnd()
    { return 100; }

// the Abyss servant rule, armor: creatures used as servants and lackeys in
// the Abyss have additional powers compared to their Prime Material
// counterparts - subtract 1 from the listed Armor Class.
inline int ddlServantAcBonus()
    { return 1; }

// the Abyss servant rule, offense: a +2 bonus to hit if the servant is of
// less than low Intelligence - the mindless ones strike the harder.
inline int ddlServantHitBonus()
    { return 2; }

// the Abyss servant rule, magic: a 10% chance of spell ability if the servant
// is of low Intelligence or higher, casting as an evil cleric of level 1d10.
inline int ddlServantCastPct()
    { return 10; }

// the Abyss doctrine: the 666-layered well of chaotic evil - the most
// numerous creatures are the demon races, a fell group of foul monstrosities
// seemingly limitless in number; their prolificacy would cause concern in
// other planes were it not for the fact that the demons always turn on each
// other - the stronger seek to dominate the weaker, the weaker conspire to
// overthrow the stronger, and alliances mean little (the demonic allies of
// one moment become the enemies of the next).
inline bool ddlAbyssDoctrine()
    { return true; }

// Pazunia, the first layer - the Plains of Infinite Portals, or the Palace of
// 1,001 Closets (named for Pazuzu, who is most often found here): the topmost
// of the uncountable Abyssal layers, a barren, dusty place without life or
// greenery baking beneath a hell-red sun, broken by three features - the huge
// holes in the earth (conduits to the various layers, functioning like
// Astral-plane conduits: those who descend are immediately taken where the
// conduit leads), the great iron portals and fortresses (the interplanar
// portals also look like large holes, creating havoc for through-travelers;
// the fortresses usually house the material bodies of higher-level demons and
// demon lords traveling astrally, guarded by servants who fight to the death
// - permanent on this plane - to protect the lord's body; the fortresses are
// usually immune to astral-viewing portals, so astral travelers cannot enter
// from the Astral plane; demons sometimes war against each other while one is
// away on the Prime, seeking to stay the enemy's physical form and either
// kill the Power or maroon it on a Prime plane - sieges are common, and the
// lords return as soon as possible if their true body is in danger), and the
// river Styx (winding across the top layer, some channels pouring into holes
// while other portals feed the river of forgetfulness with waterfalls that
// run in reverse; travelers are advised to use the boatman Charon or his
// servants). No known barriers exist in the first layer; those known in other
// layers are jealously guarded by the inhabitants, can be located in any
// terrain, and can lead to any terrain on the other side.
inline bool ddlPazuniaRule()
    { return true; }

// the demon-race census: a full listing of the general frequency of the
// various demon races is on page 35 of the Monster Manual II, with several
// additions for the Abyss - bodaks (uncommon), shadow demons (rare), and
// hordings (rare); the rulers of the various layers often maintain vast
// standing forces in their home layers; the demon lords are the most powerful
// of their race, each prince controlling one or more layers, continually at
// each other's throats with plans and counterplans to expand their domains -
// the only unifying force is their hatred of good and organized peoples; the
// exact layers inhabited by the demon princes are unrevealed, left for the
// traveler to discover.
inline bool ddlAbyssRaces()
    { return true; }

// the rumored dwellings of the demon princes: Orcus in a great palace made of
// bone rising out of ground bone meal, his guards and servants undead, ruling
// many layers from his empty halls (said to have conquered a number of Prime
// planes); Demogorgon across several layers, each a jungle filled with
// dinosaurs, wild apes and bird-like monsters besides the standard demonic
// complement; Yeenoghu's mansion the size of a city, rolling across the
// barren salt waste pulled by slaves and controlled by gnolls; Juiblex in a
// layer of living fungus and rot, all matter decaying, slimes and molds
// living off each other's world forms; Lolth controlling a number of adjacent
// planes, reached through a great web built amid a primal maelstrom; Baphomet
// at the center of an infinite maze spanning his layer and those adjacent,
// the maze changing as it passes between layers, populated by minotaurs (some
// with breath weapons and magical abilities); Fraz-Urb'Luu newly returned and
// evicting the usurpers of his absence, his realms once rivaling the Twin
// Paradises or Arvandor in beauty - but only a cruel deception over decay and
// rotting flesh; Graz'zt in a great palace filling an entire layer and
// dominating the nearby lesser lords' layers, marshaling his army against
// Orcus and Demogorgon; Kostchtchie holding only part of a single glacial
// layer filled with all evil creatures of cold, his hatred spanning the
// layers; Pazuzu with no abode, ceded the air above the surface of every
// layer - the demons depend on him (and on Charon where the Styx runs) for
// ready transportation, making him that rarest of beings, a well-liked (or at
// least tolerated) demon; Zuggtmoy with several realms scattered among the
// layers, appearing as normal environments overrun by fungus and lit by a
// purplish light, all manner of fungoid creatures inhabiting them. Demon
// lords and princes are considered Lesser Powers in their home planes; if
// slain in the Abyss they are dead - though another creature will evolve into
// a being similar to the deceased demon to fill the gap.
inline bool ddlDemonPrinces()
    { return true; }

// the Abyss servant doctrine: creatures used as servants and lackeys gain
// additional powers and abilities compared to their Prime Material
// counterparts - armor one better, the +2 mindless hit bonus, and the 10%
// evil-cleric spell ability (the three consts pin the numbers).
inline bool ddlAbyssServantRule()
    { return true; }

// the Powers of the Abyss: few Greater Powers make it their home, as they
// would have to continually deal with the upstart demon life filling the
// plane; some Powers are merely souped-up demons or powerful Prime Material
// monsters - Vaprak of the trolls and Laogzed of the troglodytes, less
// powerful than most demon princes, each ruling only part of a native layer;
// Urdlen, the evil gnome-god, in a layer of solid rock crisscrossed with the
// infinite tunnels he has carved in his hatred; the Chinese Powers Tou Mu and
// Lu Yueh in the realm called Feng-Tu - a mighty citadel rising up a forked
// branch of the Styx called the How Nai-ho, reachable by Charon and the
// charonadaemons, entered through the Kuei-Men-Kuan (the gate of demons,
// large enough for elephantine behemoths), the god of epidemics and the
// goddess of the northstar holding sway over a household of demons; and Kali,
// the black earth mother lesser goddess, controlling her entire layer of
// jagged peaks and blood-red tropical vegetation - decaying temples overgrown
// with scarlet vines and crimson flowers, her servants demons and chaotic
// evil rakshasas.
inline bool ddlAbyssPowers()
    { return true; }

}   // namespace rules
