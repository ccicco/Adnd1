# ============================================================================
# Adnd1 - tools/r1027_splice.py
# R1027 (the A2 de-wire): the misc magic live-registry splice.
#
# The round: the 23 III.E misc magic prose part headers and their 23
# pin-walking audits retire to boneyard/dmg/ (user ruling 2026-11-13);
# the 166 lua defs at content/magic_items/ go LIVE through
# items/MiscItemRegistry (the R71 MonsterRegistry Lua C API pattern,
# user ruling: build the live registry now); the walking audit role
# passes to rules/audits/r1027_misc_magic_registry.h (generated by
# tools/miscmagic_audit_gen.py, 8 labels, full-population asserts).
#
# This splice edits regtest.cpp ONLY:
#   - removes the 23 prose part header includes (R257-R279)
#   - removes the 3 chained prose pin-audit fragment includes
#     (r257/r258/r259 - r259 transitively included the other 20)
#   - adds the MiscItemRegistry include
#   - adds the R1027 registry audit fragment include
#
# ACID (the splice verifies itself against the real regtest.cpp):
#   before: exactly 23 prose includes, exactly 3 chained audit
#           includes, zero registry refs
#   after:  zero prose refs of either kind, exactly 1 registry
#           include, exactly 1 R1027 fragment include, and the
#           census pattern count (the preflight [3/5] math) is
#           exactly 934 = 949 - 23 retired + 8 new labels.
#
# Pure stdlib. Run from the repo root AFTER the boneyard move, the
# tool update, and the audit generation:
#   python3 tools/r1027_splice.py
# ============================================================================

import os
import re
import sys

OFF = "\033[0m"
RED = "\033[31m"
GREEN = "\033[32m"


def FAIL(msg):
    print(RED + "R1027 SPLICE RED: " + msg + OFF)
    sys.exit(1)


def census_patterns(src, audits_dir):
    """The preflight [3/5] math, computed the same way: the unique
    'audit: bad %d' printf patterns from regtest.cpp plus every
    rules/audits/*.h fragment."""
    import glob
    pats = set()
    for line in src.splitlines():
        m = re.search(r'printf\("([^"]*audit: bad %d)', line)
        if m:
            pats.add(m.group(1)[:-3])
    for path in glob.glob(os.path.join(audits_dir, "*.h")):
        for line in open(path).read().splitlines():
            m = re.search(r'printf\("([^"]*audit: bad %d)', line)
            if m:
                pats.add(m.group(1)[:-3])
    return len(pats)


def main():
    if not os.path.isfile("regtest.cpp"):
        FAIL("run from the repo root (regtest.cpp not found in cwd)")
    if not os.path.isfile("items/MiscItemRegistry.h") or \
       not os.path.isfile("items/MiscItemRegistry.cpp"):
        FAIL("items/MiscItemRegistry.{h,cpp} not in place yet")
    frag = os.path.join("rules", "audits", "r1027_misc_magic_registry.h")
    if not os.path.isfile(frag):
        FAIL("rules/audits/r1027_misc_magic_registry.h not generated yet"
             " (run tools/miscmagic_audit_gen.py first)")
    if not os.path.isdir(os.path.join("boneyard", "dmg")):
        FAIL("boneyard/dmg/ not in place yet (do the git mv first)")
    if os.path.isfile(os.path.join("rules", "dmg",
                                   "miscmagic_prose_part1.h")):
        FAIL("the prose headers are still in rules/dmg/ (do the git mv"
             " first)")

    src = open("regtest.cpp").read()
    lines = src.splitlines(True)

    # ---- before-gates ----------------------------------------------------
    prose = [i for i, l in enumerate(lines)
             if '#include "rules/dmg/miscmagic_prose_part' in l]
    chained = [i for i, l in enumerate(lines)
               if re.search(r'#include "rules/audits/r2\d\d'
                            r'_misc_magic_prose_part', l)]
    if len(prose) != 23:
        FAIL("expected 23 prose includes, found %d" % len(prose))
    if len(chained) != 3:
        FAIL("expected 3 chained prose audit includes, found %d"
             % len(chained))
    if "MiscItemRegistry" in src:
        FAIL("regtest.cpp already references MiscItemRegistry"
             " (splice already run?)")
    for i in sorted(set(prose + chained)):
        if not re.search(r'// R2\d\d:', lines[i]) \
           and "R835: migrated" not in lines[i]:
            FAIL("unexpected include shape at line %d: %r"
                 % (i + 1, lines[i]))

    # ---- the edit ---------------------------------------------------------
    # remove the 26 retired includes
    drop = set(prose) | set(chained)
    out = [l for i, l in enumerate(lines) if i not in drop]

    # the R1027 audit fragment rides where the r257 chain began
    anchor = ('    #include "rules/audits/r280_special_artifacts_prose.h"'
              '  // R835: migrated')
    if sum(1 for l in out if anchor in l) != 1:
        FAIL("the r280 anchor include not found exactly once")
    idx = next(i for i, l in enumerate(out) if anchor in l)
    out.insert(idx, '    #include "rules/audits/'
                    'r1027_misc_magic_registry.h"  // R1027: migrated\n')

    # the registry include rides after the MonsterRegistry include
    reg_anchor = '#include "monsters/MonsterRegistry.h"'
    ridx = None
    for i, l in enumerate(out):
        if reg_anchor in l:
            ridx = i
            break
    if ridx is None:
        FAIL("the MonsterRegistry include not found")
    out.insert(ridx + 1,
               '#include "items/MiscItemRegistry.h"  // R1027: the misc'
               ' magic item registry (the A2 de-wire)\n')

    new_src = "".join(out)

    # ---- after-gates ------------------------------------------------------
    if "miscmagic_prose" in new_src or "misc_magic_prose" in new_src:
        FAIL("a prose reference survived the splice")
    if new_src.count("MiscItemRegistry.h") != 1:
        FAIL("the registry include count is not 1")
    if new_src.count("r1027_misc_magic_registry.h") != 1:
        FAIL("the R1027 fragment include count is not 1")
    n = census_patterns(new_src, os.path.join("rules", "audits"))
    if n != 934:
        FAIL("census pattern count %d != 934 (949 - 23 + 8)" % n)

    open("regtest.cpp", "w").write(new_src)

    print(GREEN + "R1027 splice: GREEN" + OFF)
    print("  removed: 23 prose part includes + 3 chained audit includes")
    print("  added:   items/MiscItemRegistry.h +"
          " rules/audits/r1027_misc_magic_registry.h")
    print("  regtest.cpp: %d -> %d lines" % (len(lines), len(out) + 2))
    print("  census patterns: %d (949 - 23 retired + 8 registry labels)"
          % n)


if __name__ == "__main__":
    main()
