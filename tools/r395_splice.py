    s = rd(path)
    if s.count(new) == expect:
        already.append(label)
        return
    n = s.count(old)
    if n != expect:
        die('%s: old text count %d, expected %d'
            % (label, n, expect))
    wr(path, s.replace(old, new))
    applied.append(label)


